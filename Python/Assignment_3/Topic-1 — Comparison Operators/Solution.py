# Topic-1 — Comparison Operators
# Q1 to Q4


# Q1 — Predict the Output
a = 15
b = 20

print(a < b)
print(a > b)
print(a == b)
print(a != b)
print(a <= b)
print(a >= b)

# Output:
# True
# False
# False
# True
# True
# False


# Q2 — Compare Expressions
x = 10
y = 10

print(x == y)
print(x != y)
print(x < y)
print(x <= y)
print(x >= y)

# Output:
# True
# False
# False
# True
# True

# == is used for comparison.
# = is used for assignment.


# Q3 — Comparison with Arithmetic
a = 10
b = 5

print(a + b == 15)
print(a * b > 40)
print(a - b != 5)
print(a // b == 2)

# Output:
# True
# True
# False
# True


# Q4 — String Comparison
print("Python" == "Python")
print("Python" == "python")
print("Hello" != "hello")

# Output:
# True
# False
# True

# String comparison is case-sensitive.
# "Python" and "python" are considered different strings.