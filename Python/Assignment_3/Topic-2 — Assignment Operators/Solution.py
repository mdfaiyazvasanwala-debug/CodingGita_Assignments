# Q5 — Trace the Value
x = 20

x += 10
print("After += 10:", x)   # 30

x -= 5
print("After -= 5:", x)    # 25

x *= 2
print("After *= 2:", x)    # 50

x //= 5
print("After //= 5:", x)   # 10

print("Final Value:", x)   # 10


